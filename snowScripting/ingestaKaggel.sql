USE ROLE DOMO_INGEST_ROLE;
USE WAREHOUSE DOMO_WH_DEV;
USE DATABASE DOMO_DEV_BRONZE_DB;
USE SCHEMA RAW_DOMOTICA;

COPY INTO KAGGLE_SQL_DUMP_RAW (FILE_NAME, LINE_NUMBER, RAW_SQL_LINE)
FROM (
    SELECT
        METADATA$FILENAME,
        METADATA$FILE_ROW_NUMBER,
        t.$1
    FROM @STG_KAGGLE_DEV t
)
ON_ERROR = 'ABORT_STATEMENT';

-- Comprobar que entraron todas las líneas sin truncarse
SELECT
    LINE_NUMBER,
    LENGTH(RAW_SQL_LINE) AS CARACTERES,
    LEFT(RAW_SQL_LINE, 80) AS INICIO_LINEA
FROM KAGGLE_SQL_DUMP_RAW
ORDER BY LINE_NUMBER;


SELECT *
FROM KAGGLE_SQL_DUMP_RAW
LIMIT 5;


SELECT *
FROM KAGGLE_SQL_DUMP_RAW
ORDER BY line_number DESC
LIMIT 20;


