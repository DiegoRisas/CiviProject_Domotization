USE ROLE DOMO_INGEST_ROLE;
USE WAREHOUSE DOMO_WH_DEV;
USE DATABASE DOMO_DEV_BRONZE_DB;

CREATE SCHEMA IF NOT EXISTS RAW_DOMOTICA;

-- File Format para leer cada línea entera del .sql como una única columna
CREATE FILE FORMAT IF NOT EXISTS RAW_DOMOTICA.FF_SQL_DUMP_RAW
    TYPE = 'CSV'
    FIELD_DELIMITER = NONE
    RECORD_DELIMITER = '\n'
    SKIP_HEADER = 0
    COMPRESSION = 'AUTO';

-- Stage interno en DEV
CREATE STAGE IF NOT EXISTS RAW_DOMOTICA.STG_KAGGLE_DEV
    FILE_FORMAT = RAW_DOMOTICA.FF_SQL_DUMP_RAW;

-- Tabla cruda para aterrizar el dump de 172 líneas
CREATE TABLE IF NOT EXISTS RAW_DOMOTICA.KAGGLE_SQL_DUMP_RAW (
    INGESTED_AT  TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    FILE_NAME    VARCHAR,
    LINE_NUMBER  NUMBER,
    RAW_SQL_LINE VARCHAR
);

