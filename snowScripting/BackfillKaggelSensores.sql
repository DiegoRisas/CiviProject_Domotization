USE ROLE DOMO_INGEST_ROLE;
USE WAREHOUSE DOMO_WH_PRO;
USE DATABASE DOMO_PRO_BRONZE_DB;
USE SCHEMA RAW_DOMOTICA;

-- A) Backfill inicial: últimos 31 días completos (2020-06-01 a 2020-07-01) desplazados hasta hoy (2026-11-23)
INSERT INTO SENSORES_KAGGLE_RAW (SENSOR, FECHA_HORA_ORIGINAL, FECHA_HORA_SIMULADA, VALOR)
SELECT
    SENSOR,
    FECHA_HORA_ORIGINAL,
    DATEADD('day', DATEDIFF('day', DATE '2020-07-01', DATE '2026-11-23'), FECHA_HORA_ORIGINAL) AS FECHA_HORA_SIMULADA,
    VALOR
FROM KAGGLE_POOL_HISTORICO
WHERE FECHA_HORA_ORIGINAL::DATE BETWEEN DATE '2020-06-01' AND DATE '2020-07-01';

-- B) Task diaria (20:45 hora de Madrid, justo tras la ingesta de REData y Open-Meteo):
-- Inyecta cada noche las 24h correspondientes al día siguiente desplazadas al presente
CREATE OR REPLACE TASK TASK_REPLAY_KAGGLE_DAILY
    WAREHOUSE = DOMO_WH_PRO
    SCHEDULE = 'USING CRON 45 20 * * * Europe/Madrid'
AS
INSERT INTO DOMO_PRO_BRONZE_DB.RAW_DOMOTICA.SENSORES_KAGGLE_RAW
    (SENSOR, FECHA_HORA_ORIGINAL, FECHA_HORA_SIMULADA, VALOR)
SELECT
    SENSOR,
    FECHA_HORA_ORIGINAL,
    DATEADD('day', DATEDIFF('day', DATE '2020-07-01', DATE '2026-11-23'), FECHA_HORA_ORIGINAL),
    VALOR
FROM DOMO_PRO_BRONZE_DB.RAW_DOMOTICA.KAGGLE_POOL_HISTORICO
WHERE DATEADD('day', DATEDIFF('day', DATE '2020-07-01', DATE '2026-11-23'), FECHA_HORA_ORIGINAL)::DATE
      = DATEADD('day', 1, CONVERT_TIMEZONE('Europe/Madrid', CURRENT_TIMESTAMP())::DATE);

ALTER TASK TASK_REPLAY_KAGGLE_DAILY RESUME;




