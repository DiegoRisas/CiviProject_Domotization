-- 1. Comprobar que PRO Bronze tiene los 7 sensores y el rango simulado correcto
USE ROLE DOMO_DEV_TRANSFORM_ROLE;
USE WAREHOUSE DOMO_WH_DEV;

SELECT
    SENSOR,
    COUNT(*) AS FILAS,
    MIN(FECHA_HORA_SIMULADA) AS DESDE_SIMULADO,
    MAX(FECHA_HORA_SIMULADA) AS HASTA_SIMULADO
FROM DOMO_PRO_BRONZE_DB.RAW_DOMOTICA.SENSORES_KAGGLE_RAW
GROUP BY SENSOR
ORDER BY SENSOR;

-- 2. Limpiar las tablas y stage temporales usados en DEV para parsear el dump
USE ROLE DOMO_INGEST_ROLE;
USE WAREHOUSE DOMO_WH_DEV;
DROP SCHEMA IF EXISTS DOMO_DEV_BRONZE_DB.RAW_DOMOTICA CASCADE;



USE ROLE DOMO_DEV_TRANSFORM_ROLE; -- o DOMO_PRO_TRANSFORM_ROLE / DOMO_INGEST_ROLE
USE WAREHOUSE DOMO_WH_PRO;

SELECT
    SENSOR AS HABITACION,
    COUNT(*) AS TOTAL_LECTURAS,
    MIN(FECHA_HORA_SIMULADA) AS DESDE_SIMULADO,
    MAX(FECHA_HORA_SIMULADA) AS HASTA_SIMULADO,
    ROUND(MIN(VALOR), 1) AS TEMP_MIN_C,
    ROUND(AVG(VALOR), 1) AS TEMP_MEDIA_C,
    ROUND(MAX(VALOR), 1) AS TEMP_MAX_C
FROM DOMO_PRO_BRONZE_DB.RAW_DOMOTICA.SENSORES_KAGGLE_RAW
GROUP BY SENSOR
ORDER BY SENSOR;

SELECT
    SENSOR,
    FECHA_HORA_SIMULADA,
    FECHA_HORA_ORIGINAL,
    VALOR AS TEMPERATURA_C,
    INGESTED_AT
FROM DOMO_PRO_BRONZE_DB.RAW_DOMOTICA.SENSORES_KAGGLE_RAW
ORDER BY FECHA_HORA_SIMULADA DESC, SENSOR
LIMIT 50;



SELECT
    DATE_TRUNC('hour', FECHA_HORA_SIMULADA) AS FECHA_HORA_PK,
    SENSOR AS HABITACION,
    ROUND(AVG(VALOR), 2) AS TEMP_INTERIOR_MEDIA_C,
    COUNT(*) AS LECTURAS_EN_LA_HORA
FROM DOMO_PRO_BRONZE_DB.RAW_DOMOTICA.SENSORES_KAGGLE_RAW
WHERE FECHA_HORA_SIMULADA::DATE = DATE '2026-11-23'
GROUP BY 1, 2
ORDER BY 1 DESC, 2;