USE ROLE DOMO_INGEST_ROLE;
USE WAREHOUSE DOMO_WH_PRO;
USE DATABASE DOMO_PRO_BRONZE_DB;

CREATE SCHEMA IF NOT EXISTS RAW_APIS;

-- 1. Formato de fichero JSON (conserva el JSON completo por descarga)
CREATE FILE FORMAT IF NOT EXISTS RAW_APIS.FF_JSON_RAW
    TYPE = 'JSON'
    COMPRESSION = 'AUTO';

-- 2. Stage interno donde Python depositará los JSON diarios
CREATE STAGE IF NOT EXISTS RAW_APIS.STG_RAW_APIS
    FILE_FORMAT = RAW_APIS.FF_JSON_RAW;

-- 3. Tabla Bronze para precios PVPC (Red Eléctrica)
CREATE TABLE IF NOT EXISTS RAW_APIS.REE_PVPC_RAW (
    INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    TARGET_DATE DATE,
    FILE_NAME   VARCHAR,
    RAW_JSON    VARIANT
);

-- 4. Tabla Bronze para predicción horaria (AEMET)
CREATE TABLE IF NOT EXISTS RAW_APIS.AEMET_FORECAST_RAW (
    INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    MUNICIPIO   VARCHAR(10),
    FILE_NAME   VARCHAR,
    RAW_JSON    VARIANT
);


