-- 1. Warehouses dedicados (XSMALL con apagado automático tras 60s)
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS DOMO_WH_DEV
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS DOMO_WH_PRO
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- 2. Bases de datos Medallion (DEV y PRO)
CREATE DATABASE IF NOT EXISTS DOMO_PRO_BRONZE_DB;
CREATE DATABASE IF NOT EXISTS DOMO_DEV_BRONZE_DB;

CREATE DATABASE IF NOT EXISTS DOMO_DEV_SILVER_DB;
CREATE DATABASE IF NOT EXISTS DOMO_PRO_SILVER_DB;

CREATE DATABASE IF NOT EXISTS DOMO_DEV_GOLD_DB;
CREATE DATABASE IF NOT EXISTS DOMO_PRO_GOLD_DB;
/*--------------------------------------------------------------------------------------------*/
-- 3. Roles funcionales y jerarquía hacia SYSADMIN
USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS DOMO_INGEST_ROLE;
CREATE ROLE IF NOT EXISTS DOMO_DEV_TRANSFORM_ROLE;
CREATE ROLE IF NOT EXISTS DOMO_PRO_TRANSFORM_ROLE;
CREATE ROLE IF NOT EXISTS DOMO_REPORTING_ROLE;

GRANT ROLE DOMO_INGEST_ROLE        TO ROLE SYSADMIN;
GRANT ROLE DOMO_DEV_TRANSFORM_ROLE TO ROLE SYSADMIN;
GRANT ROLE DOMO_PRO_TRANSFORM_ROLE TO ROLE SYSADMIN;
GRANT ROLE DOMO_REPORTING_ROLE     TO ROLE SYSADMIN;

-- Asignación a tu usuario personal
SELECT CURRENT_USER();

GRANT ROLE DOMO_INGEST_ROLE        TO USER DIEGOSV;
GRANT ROLE DOMO_DEV_TRANSFORM_ROLE TO USER DIEGOSV;
GRANT ROLE DOMO_PRO_TRANSFORM_ROLE TO USER DIEGOSV;
GRANT ROLE DOMO_REPORTING_ROLE     TO USER DIEGOSV;

-- 4. Permisos sobre Warehouses
GRANT USAGE, OPERATE ON WAREHOUSE DOMO_WH_PRO TO ROLE DOMO_INGEST_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE DOMO_WH_PRO TO ROLE DOMO_PRO_TRANSFORM_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE DOMO_WH_PRO TO ROLE DOMO_REPORTING_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE DOMO_WH_DEV TO ROLE DOMO_DEV_TRANSFORM_ROLE;

/*--------------------------------------------------------------------------------------------*/

-- 5. Permisos de escritura por capa
-- Ingesta controla DOMO_PRO_BRONZE_DB
GRANT USAGE, CREATE SCHEMA ON DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_INGEST_ROLE;
GRANT USAGE, CREATE SCHEMA ON DATABASE DOMO_DEV_BRONZE_DB TO ROLE DOMO_INGEST_ROLE; //Innecesario, ya que:
    /*
    En un pipeline real el flujo siempre es PRO → DEV: Tus scripts diarios de REData y clima traen datos reales; la fuente de verdad debe ser siempre PRO
    (DOMO_PRO_BRONZE_DB). Producción nunca debería depender de una base de datos de desarrollo donde estás haciendo pruebas.
    
    Pero creo este permiso de ingesta para, al hacer las primeras pruebas con los scripts de python, no "ensuciar" el pro de bronze.
    */

-- dbt DEV controla Silver y Gold de DEV
GRANT USAGE, CREATE SCHEMA ON DATABASE DOMO_DEV_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE, CREATE SCHEMA ON DATABASE DOMO_DEV_GOLD_DB   TO ROLE DOMO_DEV_TRANSFORM_ROLE;

-- dbt PRO controla Silver y Gold de PRO
GRANT USAGE, CREATE SCHEMA ON DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_PRO_TRANSFORM_ROLE;
GRANT USAGE, CREATE SCHEMA ON DATABASE DOMO_PRO_GOLD_DB   TO ROLE DOMO_PRO_TRANSFORM_ROLE;

-- 6. Permisos de lectura (actuales y futuros)
-- Lectura de DOMO_PRO_BRONZE_DB para PRO y DEV
GRANT USAGE  ON DATABASE DOMO_PRO_BRONZE_DB                  TO ROLE DOMO_PRO_TRANSFORM_ROLE;
GRANT USAGE  ON ALL SCHEMAS    IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_PRO_TRANSFORM_ROLE;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_PRO_TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES     IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_PRO_TRANSFORM_ROLE;
GRANT SELECT ON FUTURE TABLES  IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_PRO_TRANSFORM_ROLE;

GRANT USAGE  ON DATABASE DOMO_PRO_BRONZE_DB                  TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE  ON ALL SCHEMAS    IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES     IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON FUTURE TABLES  IN DATABASE DOMO_PRO_BRONZE_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;

-- Lectura de PRO_SILVER y PRO_GOLD para DEV (soporte dbt --defer)
GRANT USAGE  ON DATABASE DOMO_PRO_SILVER_DB                  TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE  ON ALL SCHEMAS    IN DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES     IN DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON FUTURE TABLES  IN DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON ALL VIEWS      IN DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE DOMO_PRO_SILVER_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;

GRANT USAGE  ON DATABASE DOMO_PRO_GOLD_DB                  TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE  ON ALL SCHEMAS    IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES     IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON FUTURE TABLES  IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON ALL VIEWS      IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_DEV_TRANSFORM_ROLE;

-- Lectura exclusiva en PRO_GOLD para DOMO_REPORTING_ROLE (Snowsight / Streamlit)
GRANT USAGE  ON DATABASE DOMO_PRO_GOLD_DB                  TO ROLE DOMO_REPORTING_ROLE;
GRANT USAGE  ON ALL SCHEMAS    IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_REPORTING_ROLE;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_REPORTING_ROLE;
GRANT SELECT ON ALL TABLES     IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_REPORTING_ROLE;
GRANT SELECT ON FUTURE TABLES  IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_REPORTING_ROLE;
GRANT SELECT ON ALL VIEWS      IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_REPORTING_ROLE;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE DOMO_PRO_GOLD_DB TO ROLE DOMO_REPORTING_ROLE;

